/** Base64 data-URL → buffer, with declared size check. */
export function parseDataUrl(
  dataUrl: string,
  maxBytes: number
): { buf: Buffer; mime: string } | null {
  if (typeof dataUrl !== "string") return null;
  if (dataUrl.length > Math.ceil(maxBytes * 1.4) + 128) return null; // cheap pre-check
  const m = /^data:(image\/(?:png|jpeg|webp));base64,([A-Za-z0-9+/=]+)$/.exec(dataUrl);
  if (!m) return null;
  const [, mime, b64] = m;
  const buf = Buffer.from(b64, "base64");
  if (buf.length === 0 || buf.length > maxBytes) return null;
  return { buf, mime };
}

/** Magic-byte sniffing so a renamed .exe can't pass as a PNG. */
export function imageMime(buf: Buffer): "png" | "jpeg" | "webp" | null {
  if (buf.length < 12) return null;
  if (buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4e && buf[3] === 0x47)
    return "png";
  if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return "jpeg";
  if (
    buf.subarray(0, 4).toString("ascii") === "RIFF" &&
    buf.subarray(8, 12).toString("ascii") === "WEBP"
  )
    return "webp";
  return null;
}

export const extensionFor = (mime: "png" | "jpeg" | "webp"): "png" | "jpg" | "webp" =>
  mime === "jpeg" ? "jpg" : mime;

export const contentTypeFor = (mime: "png" | "jpeg" | "webp"): string =>
  `image/${mime}`;
